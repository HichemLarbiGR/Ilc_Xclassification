"""
Classification Metrics Module
=============================

This module provides utilities for evaluating classification models
using standard performance metrics.

The implemented metrics include accuracy, macro-averaged precision,
recall and F1-score, weighted F1-score, ROC-AUC, and the confusion
matrix.

Functions
---------
get_metrics
    Compute global classification metrics from ground-truth labels,
    predicted labels, and optional predicted probabilities.
"""


from typing import Any, Dict, Optional

import numpy as np
from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    average_precision_score,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.preprocessing import label_binarize


def get_sensitivity(cm: np.ndarray) -> float:
    tn, fp, fn, tp = cm.ravel()
    return tp / (tp + fn) if (tp + fn) else float("nan")

def get_specificity(cm: np.ndarray) -> float:
    tn, fp, fn, tp = cm.ravel()
    return tn / (tn + fp) if (tn + fp) else float("nan")

def get_metrics(
    all_labels: np.ndarray,
    all_preds: np.ndarray,
    all_probs: Optional[np.ndarray] = None,
    num_classes: int = 2,
) -> Dict[str, Any]:
    """
    Compute global classification metrics.

    Parameters
    ----------
    all_labels : np.ndarray
        Ground-truth labels for all observations.
    all_preds : np.ndarray
        Predicted labels generated by the model.
    all_probs : Optional[np.ndarray], default=None
        Predicted probabilities for each class.
    num_classes : int, default=3
        Total number of classes.

    Returns
    -------
    Dict[str, Any]
        Dictionary containing the following classification metrics:
        - accuracy
        - precision_macro
        - recall_macro
        - f1_macro
        - f1_weighted
        - auc
        - confusion_matrix
    """
    unique_labels = np.unique(all_labels)
    n_classes_present = len(unique_labels)

    # Initialize metrics with their default values.
    metrics: Dict[str, Any] = {
        "accuracy": accuracy_score(all_labels, all_preds),
        "precision_macro": float("nan"),
        "recall_macro": float("nan"),
        "f1_macro": float("nan"),
        "f1_weighted": float("nan"),
        "specificity": float("nan"),
        "sensitivity": float("nan"),
        "auprc": float("nan"),
        "auc": float("nan"),
        "confusion_matrix": confusion_matrix(
            all_labels,
            all_preds,
            labels=list(range(num_classes)),
        ),
    }

    # Compute additional metrics when more than one class is present.
    if n_classes_present > 1:
        metrics.update(
            {
                "precision_macro": precision_score(
                    all_labels,
                    all_preds,
                    average="macro",
                    zero_division=0,
                ),
                "recall_macro": recall_score(
                    all_labels,
                    all_preds,
                    average="macro",
                    zero_division=0,
                ),
                "f1_macro": f1_score(
                    all_labels,
                    all_preds,
                    average="macro",
                    zero_division=0,
                ),
                "f1_weighted": f1_score(
                    all_labels,
                    all_preds,
                    average="weighted",
                    zero_division=0,
                ),
                "sensitivity": get_sensitivity(metrics["confusion_matrix"]),
                "specificity": get_specificity(metrics["confusion_matrix"]),
            }
        )

        # Compute AUC only when predicted probabilities are available.
        if all_probs is not None:
            all_probs = np.asarray(all_probs)
            try:
                if num_classes == 2:
                    y_score = all_probs[:, 1]
                else:
                    # multi-classe : AP macro via one-vs-rest
                    labels_bin = label_binarize(
                        all_labels, classes=list(range(num_classes))
                    )
                    metrics["auprc"] = float(
                        average_precision_score(labels_bin, all_probs, average="macro")
                    )
                    y_score = None
                if y_score is not None:
                    metrics["auprc"] = float(
                        average_precision_score(all_labels, y_score)
                    )
            except ValueError as e:
                print(f"[AUPRC] failed: {type(e).__name__}: {e}")
                metrics["auprc"] = None

            # AUC (existant)
            try:
                if num_classes == 2:
                    metrics["auc"] = roc_auc_score(all_labels, all_probs[:, 1])
                else:
                    labels_bin = label_binarize(
                        all_labels, classes=list(range(num_classes))
                    )
                    metrics["auc"] = roc_auc_score(
                        labels_bin, all_probs,
                        multi_class="ovr", average="macro",
                    )
            except Exception as e:
                print(f"[AUC] failed: {type(e).__name__}: {e}")
                metrics["auc"] = None

    return metrics
